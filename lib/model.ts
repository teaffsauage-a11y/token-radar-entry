// Token Radar v1 — model radar-2.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and adds pre-token protocols below the floor: the early rows the
// radar exists to find. A protocol is pre-token when its record carries no
// token (no market cap, no CoinGecko id, no symbol); live-token protocols are
// kept apart and shown at their market cap, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures — no protocol
// name is ever special-cased, the same function scores every row:
//
//   base        = tvl_usd x 0.22
//                 (a token's fully diluted value is usually a fraction of the
//                 value locked; 0.22 is the model's single scale, stated on
//                 the dashboard, not fitted to any one protocol)
//   growth      = clamp(change_7d, -50, +80) per cent
//   growthMult  = 1 + (growth / 100) x 0.8 when growth is positive,
//                 1 + (growth / 100) x 1.0 when growth is negative
//                 (asymmetric on purpose: TVL leaving is a stronger signal
//                 than TVL arriving — a protocol down 40% in a week is
//                 discounted to 0.60x, while one up 40% is only lifted to
//                 1.32x. Unreported growth counts as -5%, mildly negative
//                 rather than neutral: no momentum figure is not the same
//                 as flat momentum. The +80 cap stops one wild week — the
//                 snapshot has a +4,448% outlier — from deciding the board)
//   maturity    = 0.55 + 0.45 x (1 - exp(-age_days / 540))
//                 (age since first listed, the record of how long a protocol
//                 has run with no token. Diminishing returns: 180 days gives
//                 ~0.68, 540 days ~0.83, 1,100 days ~0.94. A young protocol
//                 is discounted for being unproven, an old one is not
//                 rewarded without limit. Unknown age uses 365 days.)
//   breadth     = 1 + 0.03 x min(chains - 1, 5), at most 1.15
//                 (each extra chain the protocol runs on is a small moat:
//                 distribution across chains, capped so a 40-chain index
//                 does not outrank real usage)
//   implied     = max(1, round(base x growthMult x maturity x breadth))
//
// Why this shape, in one line: size sets the scale, growth and survival set
// the multiple, breadth is a tie-breaker. A stagnant giant can be outranked
// by a smaller protocol that is growing fast and has run for years — that is
// what a launch radar is for.

